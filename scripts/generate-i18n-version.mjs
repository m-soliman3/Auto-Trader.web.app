#!/usr/bin/env node
/**
 * Stamps a content hash of the shipped translation bundles into
 * `src/environments/i18n-version.ts`.
 *
 * The bundles are copied to `/i18n/<lang>.json` verbatim by the assets glob in
 * angular.json, so unlike the JS/CSS output they never get a filename hash of
 * their own. That left no way to tell a stale bundle from a current one, so they
 * were served `no-store` and every full page load re-downloaded ~110KB of
 * gzipped JSON. Hashing the contents into the request URL gives each revision a
 * distinct URL, so the bundles can be cached for a year (see the `/i18n/**`
 * headers in firebase.json) while a translation edit still reaches users on the
 * next deploy.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const i18nDir = join(root, 'public', 'i18n');
const outFile = join(root, 'src', 'environments', 'i18n-version.ts');

// Dotfiles in here are sync bookkeeping for the translation scripts rather than
// shipped bundles — firebase.json's `**/.*` ignore keeps them out of the deploy,
// so they must not move the hash either.
const bundles = readdirSync(i18nDir)
  .filter((name) => name.endsWith('.json') && !name.startsWith('.'))
  .sort();

if (bundles.length === 0) {
  throw new Error(`No translation bundles found in ${i18nDir}`);
}

const hash = createHash('sha256');
for (const name of bundles) {
  // The name goes in alongside the contents so that adding a new language
  // changes the version even if it somehow duplicates an existing bundle.
  hash.update(name);
  hash.update(readFileSync(join(i18nDir, name)));
}
const version = hash.digest('hex').slice(0, 12);

writeFileSync(
  outFile,
  `// Generated by scripts/generate-i18n-version.mjs — do not edit by hand.
// Refreshed automatically by the \`prebuild\` npm hook.
export const I18N_VERSION = '${version}';
`,
);

console.log(`i18n version ${version} (${bundles.length} bundles) -> ${outFile}`);
